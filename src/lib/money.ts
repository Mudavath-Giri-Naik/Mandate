/**
 * Money is stored and transmitted in paise (integers) everywhere — database,
 * API payloads, Razorpay. Formatting to rupees happens only at render time.
 */
export function formatPaise(paise: number): string {
  return new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: paise % 100 === 0 ? 0 : 2,
    maximumFractionDigits: 2,
  }).format(paise / 100);
}
